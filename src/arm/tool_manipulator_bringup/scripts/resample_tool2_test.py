#!/usr/bin/env python3
"""Resample the test tool2 entry and reviewed vertical Cartesian descent."""
import argparse
import copy
from pathlib import Path
import sys

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]/'tool_change_min'))
from tool_change_min.kinematics import ArmKinematics
from resample_tool_paths import resample


def resample_vertical_tool2(data, descent, model, period=.5):
    policy = data['vertical_descent']
    if policy['start_point'] != 16 or policy['distance_m'] != .095:
        raise ValueError('test tool2 requires a 95 mm descent from point 16')
    vertices = np.array([p['positions_rad'] for p in data['points']])
    fine = np.array(descent['positions_rad'], dtype=float)
    if (data['joint_names'] != list(model.joint_names) or
            descent.get('joint_names') != data['joint_names'] or
            descent.get('frame_id') != 'base_actuator' or descent.get('tip_link') != 'tcp_link'):
        raise ValueError('invalid test tool2 Cartesian chain or joint order')
    if (vertices.shape != (17, 6) or fine.ndim != 2 or fine.shape[1] != 6 or
            len(fine) < 2 or not np.isfinite(fine).all()):
        raise ValueError('invalid test tool2 vertical IK points')
    if not np.array_equal(fine[0], vertices[15]) or not np.array_equal(fine[-1], vertices[16]):
        raise ValueError('vertical IK endpoints must equal points 16 and 17 exactly')
    poses = np.array([model.fk(q)[:3, 3] for q in fine])
    if (np.max(np.abs(poses[:, :2]-poses[-1, :2])) > 1e-7 or
            abs(poses[0, 2]-poses[-1, 2]-.095) > 1e-7 or
            np.any(np.diff(poses[:, 2]) >= 0.) or
            not all(model.within_limits(q, .02) for q in fine)):
        raise ValueError('vertical IK violates XYZ constraints or joint margins')
    expanded = copy.deepcopy(data)
    expanded['points'] = copy.deepcopy(data['points'][:16]) + [
        dict(time_from_start_sec=float(i+16), positions_rad=q.tolist())
        for i, q in enumerate(fine[1:])]
    result = resample(expanded, period)
    indices = result['source_point_indices']
    result['source_point_indices'] = indices[:16]+[indices[-1]]
    result['vertical_descent']['start_index'] = indices[15]
    # Verify the joint interpolation actually sent to the manager, too.
    points = np.array([p['positions_rad'] for p in result['points'][indices[15]:]])
    checks = np.vstack((points, (points[:-1]+points[1:])/2))
    xyz = np.array([model.fk(q)[:3, 3] for q in checks])
    if np.max(np.abs(xyz[:, :2]-poses[-1, :2])) > .00005:
        raise ValueError('resampled vertical descent exceeds 0.05 mm XY error')
    return result


def generate(source, period=.5):
    source = Path(source)
    data = yaml.safe_load(source.read_text())
    sample_file = data['vertical_descent']['sample_file']
    if Path(sample_file).name != sample_file:
        raise ValueError('vertical sample file must be in the test config directory')
    descent = yaml.safe_load((source.parent/sample_file).read_text())
    package = Path(__file__).resolve().parents[1]
    model = ArmKinematics(package.parent/'tool_manipulator_description/urdf/tool_manipulator.urdf.xacro',
                          package/'config/hardware.yaml')
    return resample_vertical_tool2(data, descent, model, period)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('--period', type=float, default=.5)
    args = parser.parse_args()
    print('# Generated by resample_tool2_test.py; preserve the Cartesian IK descent.')
    print(yaml.safe_dump(generate(args.source, args.period), sort_keys=False), end='')
